import { afterAll, beforeAll, describe, expect, it } from 'vitest';

import { pollOnce, type ReportWorkerDeps } from '../../src/modules/reports/reports.worker.js';
import { createTestApp, type TestApp } from '../helpers/app.js';

const REPORT_FIELDS = `
  id status attempts error downloadUrl createdAt startedAt completedAt
  job { id }
  requestedBy { name }
`;

interface ReportShape {
  id: string;
  status: string;
  attempts: number;
  error: string | null;
  downloadUrl: string | null;
  createdAt: string;
  startedAt: string | null;
  completedAt: string | null;
  job: { id: string };
  requestedBy: { name: string };
}

describe('reports', () => {
  let app: TestApp;
  let alice: string;
  let dave: string;
  let bob: string;
  let jobId: string;
  let reportId: string;
  let workerDeps: ReportWorkerDeps;

  const requestReport = (token: string, id: string) =>
    app.graphql<{ requestReport: ReportShape }>(
      `mutation { requestReport(jobId: "${id}") { ${REPORT_FIELDS} } }`,
      { token },
    );

  const getReport = (token: string, id: string) =>
    app.graphql<{ report: ReportShape }>(`{ report(id: "${id}") { ${REPORT_FIELDS} } }`, { token });

  beforeAll(async () => {
    app = await createTestApp();
    await app.resetDatabase();
    [alice, dave, bob] = await Promise.all([
      app.loginAs('alice@contractor.test'),
      app.loginAs('dave@contractor.test'),
      app.loginAs('bob@homeowner.test'),
    ]);
    workerDeps = {
      queue: app.container.queue,
      reports: app.container.services.reports,
      logger: app.container.logger,
    };

    const created = await app.graphql<{ createJob: { id: string } }>(
      `mutation { createJob(input: { description: "Kitchen remodel", location: { addressLine1: "1 Main St", city: "Austin", state: "TX", postalCode: "78701" }, costCents: 2500000 }) { id } }`,
      { token: alice },
    );
    jobId = created.data!.createJob.id;
    await app.graphql(
      `mutation { addHomeowner(jobId: "${jobId}", email: "bob@homeowner.test") { id } }`,
      { token: alice },
    );
    await app.graphql(
      `mutation { sendMessage(jobId: "${jobId}", body: "Demolition starts Monday.") { id } }`,
      {
        token: alice,
      },
    );
    await app.graphql(
      `mutation { sendMessage(jobId: "${jobId}", body: "Great, thanks!") { id } }`,
      {
        token: bob,
      },
    );
  });

  afterAll(() => app.close());

  it('only the owning contractor can request a report', async () => {
    const asBob = await requestReport(bob, jobId);
    const asDave = await requestReport(dave, jobId);
    const unknownJob = await requestReport(alice, '019a0000-0000-7000-8000-0000000000ee');

    expect(asBob.errors?.[0]?.extensions?.code).toBe('FORBIDDEN');
    expect(asDave.errors?.[0]?.extensions?.code).toBe('NOT_FOUND');
    expect(unknownJob.errors?.[0]?.extensions?.code).toBe('NOT_FOUND');
  });

  it('queues the report as PENDING', async () => {
    const result = await requestReport(alice, jobId);

    expect(result.errors).toBeUndefined();
    reportId = result.data!.requestReport.id;
    expect(result.data?.requestReport).toMatchObject({
      status: 'PENDING',
      attempts: 0,
      error: null,
      downloadUrl: null,
      job: { id: jobId },
      requestedBy: { name: 'Alice Contractor' },
    });
  });

  it('is generated by the worker through SQS and uploaded to S3', async () => {
    let report: ReportShape | undefined;
    for (let attempt = 0; attempt < 15 && report?.status !== 'COMPLETED'; attempt += 1) {
      await pollOnce(workerDeps, { maxMessages: 10, waitSeconds: 1 });
      report = (await getReport(alice, reportId)).data?.report;
    }

    expect(report).toMatchObject({ status: 'COMPLETED', attempts: 1, error: null });
    expect(report?.startedAt).toEqual(expect.any(String) as string);
    expect(report?.completedAt).toEqual(expect.any(String) as string);
    expect(report?.downloadUrl).toMatch(/^http/);

    const download = await fetch(report!.downloadUrl!);
    const body = Buffer.from(await download.arrayBuffer());

    expect(download.status).toBe(200);
    expect(download.headers.get('content-type')).toBe('application/pdf');
    expect(body.subarray(0, 5).toString()).toBe('%PDF-');
    expect(body.length).toBeGreaterThan(1_000);
  });

  it('keeps the report private to the owning contractor', async () => {
    const asDave = await getReport(dave, reportId);
    const asBob = await getReport(bob, reportId);

    expect(asDave.errors?.[0]?.extensions?.code).toBe('NOT_FOUND');
    expect(asBob.errors?.[0]?.extensions?.code).toBe('FORBIDDEN');
  });
});
